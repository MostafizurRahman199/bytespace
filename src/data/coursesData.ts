// Helper to get courses for any category (with fallback to related or Featured)
export function getCoursesForCategory(category: string): Course[] {
  if (COURSES_BY_CATEGORY[category]) {
    return COURSES_BY_CATEGORY[category];
  }
  // Related aliases
  if (category === "Creative Marketing") {
    return COURSES_BY_CATEGORY["Creative Marketing"] || COURSES_BY_CATEGORY["Marketing"];
  }
  if (category === "Digital Illustration") {
    return COURSES_BY_CATEGORY["Digital Illustration"] || COURSES_BY_CATEGORY["Drawing & Painting"];
  }
  if (category === "Graphic Design") {
    return COURSES_BY_CATEGORY["Graphic Design"] || COURSES_BY_CATEGORY["Drawing & Painting"];
  }
  if (category === "Crafts") {
    return COURSES_BY_CATEGORY["Crafts"] || COURSES_BY_CATEGORY["Drawing & Painting"];
  }
  if (category === "Film & Video") {
    return COURSES_BY_CATEGORY["Film & Video"] || COURSES_BY_CATEGORY["Photography"];
  }
  if (category === "Freelance & Entrepreneurship") {
    return COURSES_BY_CATEGORY["Freelance & Entrepreneurship"] || COURSES_BY_CATEGORY["Productivity"];
  }
  // Default fallback
  return COURSES_BY_CATEGORY["Featured"];
}
